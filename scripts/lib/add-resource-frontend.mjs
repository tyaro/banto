/**
 * `pnpm banto add resource` のフロント側のテンプレート（ResourcePage の定義・ルート 3 本・
 * メッセージのキー）。手本は items（ADR-0030、docs/recipes/add-resource.md 手順 7・8）。
 * ナビの項目は定義の `nav` から導かれるので、navigation.ts には触らない。
 */

function schemaField(spec, field) {
	const lines = [
		`\t\t\tname: '${field.name}',`,
		`\t\t\tget label() {\n\t\t\t\treturn m['${spec.camel}.field${field.pascal}']();\n\t\t\t},`,
		`\t\t\ttype: '${field.type}'`
	];
	if (field.required) lines.push(`\t\t\trequired: true`);
	if (field.min !== undefined) lines.push(`\t\t\tmin: ${field.min}`);
	if (field.max !== undefined) lines.push(`\t\t\tmax: ${field.max}`);
	if (field.type === 'number') lines.push(`\t\t\tvalidate: integerValidate`);
	// 最後の行以外にカンマを付ける（先頭 2 行は付いている）。
	const [name, label, ...rest] = lines;
	return `\t\t{\n${[name, label, rest.join(',\n')].join('\n')}\n\t\t}`;
}

export function resourceTs(spec) {
	const { name, kebab, camel } = spec;
	const hasNumber = spec.fields.some((field) => field.type === 'number');
	const integerValidate = hasNumber
		? `
// The Rust input takes an \`i64\`, so a fractional value is rejected here too
// instead of after a round trip. An emptied optional input is not a number yet.
const integerValidate = (value: unknown): string | null =>
	value === '' || value === null || value === undefined || Number.isInteger(Number(value))
		? null
		: m['validation.integer']();
`
		: '';
	const description = spec.description ? `\tdescription: () => m['${camel}.description'](),\n` : '';
	return `/**
 * The \`${name}\` resource definition (ADR-0030): form schema + registration
 * object. Field names match the Rust input (\`core/src/${name}.rs\`) field for
 * field, and the rules here mirror its validation.
 *
 * Generated by \`pnpm banto add resource\` (docs/recipes/add-resource.md).
 * Ordinary code from here on: edit it by hand.
 */
import { Table2 } from '@lucide/svelte';
import type { FormSchema } from '@banto/forms';
import * as m from '#lib/paraglide/messages.js';
import { defineResource } from '#lib/resource/types.js';
${integerValidate}
// Labels are getters: this module is evaluated before the locale is set, so
// a message read here at load time would freeze to the base locale (see
// resources/items.ts in the template for the long version).
export const ${camel}Schema: FormSchema = {
	fields: [
${spec.fields.map((field) => schemaField(spec, field)).join(',\n')},
		{
			name: 'updatedAt',
			get label() {
				return m['${camel}.fieldUpdatedAt']();
			},
			type: 'date',
			readonly: true
		}
	]
};

export const ${camel}Resource = defineResource({
	name: '${name}',
	path: '/${kebab}',
${description}	nav: {
		icon: Table2,
		label: () => m['nav.${camel}']()
	},
	get label() {
		return m['${camel}.resourceLabel']();
	},
	schema: ${camel}Schema,
	capabilities: { list: true, create: true, edit: true, delete: true }
});
`;
}

