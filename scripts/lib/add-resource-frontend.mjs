/** 足すメッセージのキーと文言（`locale` は 'ja' か 'en'）。 */
export function messageEntries(spec, locale) {
	const entries = [
		[`nav.${spec.camel}`, spec.label[locale]],
		[`${spec.camel}.resourceLabel`, spec.label[locale]]
	];
	if (spec.description) entries.push([`${spec.camel}.description`, spec.description[locale]]);
	for (const field of spec.fields)
		entries.push([`${spec.camel}.field${field.pascal}`, field.label[locale]]);
	entries.push([`${spec.camel}.fieldUpdatedAt`, locale === 'ja' ? '更新日' : 'Updated']);
	return entries;
}
